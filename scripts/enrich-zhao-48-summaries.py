def main():
    print(f"[*] Bắt đầu cập nhật metadata và nguyên lý độc nhất cho toàn bộ 48 bài giảng...")
    updated_count = 0

    for lesson_num, meta in LESSON_METADATA.items():
        pattern = f"zhao48_bai{lesson_num:02d}_*.json"
        matched_files = list(DATA_DIR.glob(pattern))
        if not matched_files:
            print(f"[!] Không tìm thấy file cho bài {lesson_num}")
            continue

        file_path = matched_files[0]
        with open(file_path, "r", encoding="utf-8") as fp:
            data = json.load(fp)

        # Cập nhật thông tin chuẩn
        data["title"] = f"Triệu Hâm Hâm 48 Kỳ Lý Trung Cuộc - Bài {lesson_num}: {meta['title']}"
        data["red"] = meta["red"]
        data["black"] = meta["black"]
        data["event"] = meta["event"]
        data["date"] = meta["date"]
        data["result"] = meta["result"]
        data["opening"] = meta["opening"]

        # Giữ nguyên đúng 1 chiến thuật chính duy nhất (bỏ keyword spam)
        primary_tactic = meta["tactic"]
        data["detectedPrinciples"] = [primary_tactic]

        # Cập nhật phần summary với dẫn chứng chuẩn
        data["summary"] = {
            "title": f"Bài {lesson_num}: {meta['title']}",
            "corePrinciple": meta["corePrinciple"],
            "evidenceQuote": meta["evidenceQuote"],
            "tactics": [primary_tactic],
        }

        with open(file_path, "w", encoding="utf-8") as fp:
            json.dump(data, fp, ensure_ascii=False, indent=2)

        updated_count += 1
        print(f" [✓] Bài {lesson_num:02d}: {meta['title']} ({meta['red']} vs {meta['black']}) -> {primary_tactic}")

    print(f"\n[+] HOÀN TẤT: Đã cập nhật thành công {updated_count}/48 bài giảng với nguyên lý độc nhất!")


if __name__ == "__main__":
    main()
